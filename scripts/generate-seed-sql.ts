/**
 * Turns the bundled seed data into supabase/seed.sql so the demo content and the
 * database never drift apart. Run it with `npm run db:seed` after editing
 * anything in src/data, then paste the output into the Supabase SQL editor.
 *
 * Node strips the type-only imports in src/data, so this runs without a build step.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { events, news } from '../src/data/content.ts'
import { tournaments } from '../src/data/tournaments.ts'
import { sports, universities } from '../src/data/universities.ts'

type Value = string | number | boolean | null | undefined

const q = (value: Value): string => {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return `'${value.replace(/'/g, "''")}'`
}

const row = (values: Value[]) => `  (${values.map(q).join(', ')})`

function insert(table: string, columns: string[], rows: Value[][]): string {
  return [
    `insert into ${table} (${columns.join(', ')}) values`,
    rows.map(row).join(',\n'),
    `on conflict (id) do update set`,
    columns
      .filter((column) => column !== 'id')
      .map((column) => `  ${column} = excluded.${column}`)
      .join(',\n'),
    ';',
    '',
  ].join('\n')
}

const sql = [
  '-- Generated by `npm run db:seed` from src/data — edit the TypeScript, not this file.',
  '-- Safe to re-run: every statement upserts on the primary key.',
  '',
  insert(
    'universities',
    ['id', 'name_en', 'name_ka', 'short_name', 'city_en', 'city_ka', 'color', 'logo_url', 'banner_url'],
    universities.map((item) => [
      item.id,
      item.name.en,
      item.name.ka,
      item.shortName,
      item.city.en,
      item.city.ka,
      item.color,
      item.logoUrl,
      item.bannerUrl,
    ]),
  ),
  insert(
    'sports',
    ['id', 'name_en', 'name_ka', 'blurb_en', 'blurb_ka'],
    sports.map((item) => [item.id, item.name.en, item.name.ka, item.blurb.en, item.blurb.ka]),
  ),
  insert(
    'tournaments',
    [
      'id',
      'sport_id',
      'host_university_id',
      'title_en',
      'title_ka',
      'summary_en',
      'summary_ka',
      'format_en',
      'format_ka',
      'status',
      'start_date',
      'end_date',
      'venue_en',
      'venue_ka',
      'city_en',
      'city_ka',
      'level',
      'fee',
      'slots',
      'slots_taken',
      'registration_deadline',
      'image_url',
    ],
    tournaments.map((item) => [
      item.id,
      item.sportId,
      item.hostUniversityId,
      item.title.en,
      item.title.ka,
      item.summary.en,
      item.summary.ka,
      item.format.en,
      item.format.ka,
      item.status,
      item.startDate,
      item.endDate,
      item.venue.en,
      item.venue.ka,
      item.city.en,
      item.city.ka,
      item.level,
      item.fee,
      item.slots,
      item.slotsTaken,
      item.registrationDeadline,
      item.imageUrl,
    ]),
  ),
  insert(
    'events',
    [
      'id',
      'title_en',
      'title_ka',
      'summary_en',
      'summary_ka',
      'kind',
      'starts_at',
      'venue_en',
      'venue_ka',
      'city_en',
      'city_ka',
      'university_id',
      'ticket_url',
      'image_url',
    ],
    events.map((item) => [
      item.id,
      item.title.en,
      item.title.ka,
      item.summary.en,
      item.summary.ka,
      item.kind,
      item.startsAt,
      item.venue.en,
      item.venue.ka,
      item.city.en,
      item.city.ka,
      item.universityId,
      item.ticketUrl,
      item.imageUrl,
    ]),
  ),
  insert(
    'news',
    [
      'id',
      'slug',
      'title_en',
      'title_ka',
      'excerpt_en',
      'excerpt_ka',
      'body_en',
      'body_ka',
      'sport_id',
      'university_id',
      'published_at',
      'is_announcement',
      'read_minutes',
      'image_url',
    ],
    news.map((item) => [
      item.id,
      item.slug,
      item.title.en,
      item.title.ka,
      item.excerpt.en,
      item.excerpt.ka,
      item.body.en,
      item.body.ka,
      item.sportId,
      item.universityId,
      item.publishedAt,
      item.isAnnouncement,
      item.readMinutes,
      item.imageUrl,
    ]),
  ),
].join('\n')

const outPath = resolve(dirname(fileURLToPath(import.meta.url)), '../supabase/seed.sql')
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, sql, 'utf8')
console.log(`Wrote ${outPath}`)
