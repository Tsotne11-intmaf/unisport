/**
 * Turns the bundled seed data into supabase/seed.sql so the demo content and the
 * database never drift apart. Run it with `npm run db:seed` after editing
 * anything in src/data, then paste the output into the Supabase SQL editor.
 *
 * Node strips the type-only imports in src/data, so this runs without a build step.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { events, news } from '../src/data/content.ts'
import { tournaments } from '../src/data/tournaments.ts'
import { sports, universities } from '../src/data/universities.ts'

/** Marks a value that is already SQL and must not be quoted again. A plain
    object rather than a class, since Node strips types without compiling. */
interface Raw {
  readonly sql: string
}
const isRaw = (value: unknown): value is Raw =>
  typeof value === 'object' && value !== null && 'sql' in value

const json = (value: unknown): Raw => ({
  sql: `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`,
})

type Value = string | number | boolean | null | undefined | string[] | Raw

const quote = (value: string) => `'${value.replace(/'/g, "''")}'`

const q = (value: Value): string => {
  if (value === null || value === undefined) return 'null'
  if (isRaw(value)) return value.sql
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  // Postgres text[] literal, so a line-up round-trips as an array.
  if (Array.isArray(value)) return `array[${value.map(quote).join(', ')}]::text[]`
  return quote(value)
}

const row = (values: Value[]) => `  (${values.map(q).join(', ')})`

function insert(table: string, columns: string[], rows: Value[][]): string {
  return [
    `insert into ${table} (${columns.join(', ')}) values`,
    rows.map(row).join(',\n'),
    `on conflict (id) do update set`,
    columns
      .filter((column) => column !== 'id')
      .map((column) => `  ${column} = excluded.${column}`)
      .join(',\n'),
    ';',
    '',
  ].join('\n')
}

